/** 当前语言（模块状态；由 setLang/initLang 维护） */
export var currentLang = DEFAULT_LANG;

function normalize(value) {
  var v = String(value === undefined || value === null ? '' : value).trim().toLowerCase();
  if (!v) return '';
  if (v === 'zh' || v.indexOf('zh-') === 0 || v.indexOf('zh_') === 0) return 'zh';
  if (v === 'en' || v.indexOf('en-') === 0 || v.indexOf('en_') === 0) return 'en';
  return '';   /* 不是我们支持的语言 → 交给下一优先级 */
}

export function isSupportedLang(value) { return normalize(value) !== ''; }

/** 解析语言（纯函数，便于单测）：按上面 5 级优先级 */
export function resolveLang(opts) {
  var o = opts || {};
  return normalize(o.url) || normalize(o.stored) || normalize(o.host) || normalize(o.navigator) || DEFAULT_LANG;
}

export function lookup(key, lang) {
  var table = MESSAGES[key];
  var l = normalize(lang) || currentLang;
  if (table) {
    if (table[l]) return table[l];
    if (table.zh) return table.zh;      /* 缺 en → 明确降级到中文 */
  }
  return String(key);                    /* 连 key 都没有 → 显示 key 本身，绝不 undefined */
}

/* task-C5S1V 批次 A 的产品规则：给**模块**用的 t/format **只在「使用点」调用**。
   反例：export var NO_NAME_TEXT = t('session.noName') —— 这是**模块加载期求值** ⇒ 语言被冻结（切语言后它不会变）。
   正确：写成函数（noNameText()）或在使用处直接调 t() ✓ */
export function t(key, lang) { return lookup(key, lang); }

/** 占位符替换（模板也进表：{name} 形式）——**只有这一份**格式化实现，别在 JS 里按语言拼标点。
    缺失的参数替换成空串，绝不渲染 undefined。 */
export function format(template, params) {
  var p = params || {};
  return String(template === undefined || template === null ? '' : template)
    .replace(/\{(\w+)\}/g, function (m, k) { return (p[k] === undefined || p[k] === null) ? '' : String(p[k]); });
}

/** 模板里用到的占位符集合（判据用它保证 zh/en 占位符一致） */
export function placeholdersOf(template) {
  var out = [], re = /\{(\w+)\}/g, m;
  while ((m = re.exec(String(template || ''))) !== null) if (out.indexOf(m[1]) < 0) out.push(m[1]);
  return out.sort();
}

export function setLang(lang) {
  var l = normalize(lang) || DEFAULT_LANG;
  currentLang = l;
  try { if (typeof localStorage !== 'undefined') localStorage.setItem(LANG_KEY, l); } catch (e) { /* 存不了只用本次会话 */ }
  return l;
}

/** 从环境探测一次（URL > localStorage > 宿主 html[lang] > navigator > zh） */
export function detectLang(env) {
  var e = env || {};
  var url = '';
  try { url = new URLSearchParams((e.search === undefined ? (typeof location !== 'undefined' ? location.search : '') : e.search)).get('lang') || ''; } catch (err) { url = ''; }
  var stored = '';
  try { stored = (e.storage === undefined ? (typeof localStorage !== 'undefined' ? localStorage.getItem(LANG_KEY) : '') : e.storage) || ''; } catch (err) { stored = ''; }
  var host = e.host;
  if (host === undefined) {
    host = '';
    try {
      var pd = (typeof window !== 'undefined' && window.parent && window.parent !== window) ? window.parent.document : null;
      if (pd && pd.documentElement) host = pd.documentElement.getAttribute('lang') || '';
    } catch (err) { host = ''; }     /* 跨源 → 交给下一级 */
  }
  var nav = e.navigator;
  if (nav === undefined) nav = (typeof navigator !== 'undefined' ? navigator.language : '');
  return resolveLang({ url: url, stored: stored, host: host, navigator: nav });
}

/** 给 index.html 里带 data-i18n* 的静态外壳套上当前语言的文案（只改文本，不动结构） */
export function applyShell(root, lang) {
  var doc = root || (typeof document !== 'undefined' ? document : null);
  if (!doc || !doc.querySelectorAll) return 0;
  var l = normalize(lang) || currentLang;
  var n = 0;
  Array.prototype.forEach.call(doc.querySelectorAll('[data-i18n]'), function (el) {
    var key = el.getAttribute('data-i18n');
    if (!key) return;
    el.textContent = lookup(key, l); n++;
  });
  Array.prototype.forEach.call(doc.querySelectorAll('[data-i18n-title]'), function (el) {
    var key = el.getAttribute('data-i18n-title'); if (!key) return;
    el.setAttribute('title', lookup(key, l)); n++;
  });
  Array.prototype.forEach.call(doc.querySelectorAll('[data-i18n-aria]'), function (el) {
    var key = el.getAttribute('data-i18n-aria'); if (!key) return;
    el.setAttribute('aria-label', lookup(key, l)); n++;
  });
  Array.prototype.forEach.call(doc.querySelectorAll('[data-i18n-placeholder]'), function (el) {
    var key = el.getAttribute('data-i18n-placeholder'); if (!key) return;
    el.setAttribute('placeholder', lookup(key, l)); n++;
  });
  if (doc.documentElement) { try { doc.documentElement.setAttribute('lang', l === 'en' ? 'en' : 'zh-CN'); } catch (e) {} }
  return n;
}

/** 初始化：探测 → 记住 → 返回语言 */
export function initLang(env) {
  var l = detectLang(env);
  currentLang = l;
  return l;
}